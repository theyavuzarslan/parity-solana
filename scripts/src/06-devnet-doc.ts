// Write keys/<cluster>.json (all public addresses) and, on devnet, docs/devnet.md (non-secret).
import { writeFileSync } from "node:fs";
import { join } from "node:path";
import {
  CLUSTER, KEYS, PROGRAM_ID, ROOT, configPda, demoPda, deployer, insurancePda, keypair, marketPda,
  offerPda, priceFeedPda, program, ratePda, readMints, vaultPda,
} from "./env.js";
import { MARKETS, RATES } from "./markets.js";

async function main() {
  const mints = readMints();
  const maker = keypair("maker").publicKey, keeper = keypair("keeper").publicKey, faucet = keypair("faucet").publicKey;
  const p = program();
  const offers = (await p.account.makerOffer.all()).map((o: any) => ({
    address: o.publicKey.toBase58(), marketId: o.account.marketId, nonce: o.account.nonce.toString(),
    makerSide: Object.keys(o.account.makerSide)[0], mint: o.account.mint.equals(mints.usdg) ? "USDG" : "USDC",
    spreadBps: o.account.spreadBps,
  }));
  const out = {
    cluster: CLUSTER,
    programId: PROGRAM_ID.toBase58(),
    admin: deployer().publicKey.toBase58(),
    maker: maker.toBase58(), keeper: keeper.toBase58(), faucetMintAuthority: faucet.toBase58(),
    mints: { usdc: mints.usdc.toBase58(), usdg: mints.usdg.toBase58() },
    config: configPda().toBase58(), demoState: demoPda().toBase58(),
    vaults: { usdc: vaultPda(mints.usdc).toBase58(), usdg: vaultPda(mints.usdg).toBase58() },
    insurance: { usdc: insurancePda(mints.usdc).toBase58(), usdg: insurancePda(mints.usdg).toBase58() },
    rates: Object.fromEntries(RATES.map((r) => [r.code, ratePda(r.code).toBase58()])),
    markets: MARKETS.map((m) => ({
      id: m.id, symbol: m.symbol, address: marketPda(m.id).toBase58(),
      priceA: priceFeedPda(m.feedA).toBase58(), priceB: m.feedB ? priceFeedPda(m.feedB).toBase58() : undefined,
    })),
    offers,
    generatedAt: new Date().toISOString(),
  };
  writeFileSync(join(KEYS, `${CLUSTER}.json`), JSON.stringify(out, null, 2));
  console.log(`wrote keys/${CLUSTER}.json (${offers.length} offers)`);
  if (CLUSTER !== "devnet") return;

  const ex = (a: string) => `[\`${a}\`](https://explorer.solana.com/address/${a}?cluster=devnet)`;
  const md = `# Devnet deployment

Generated by \`scripts/src/06-devnet-doc.ts\` on ${out.generatedAt}. Public addresses only; no keys.

**Prices on devnet are admin-relayed reference prices** (demo mode on, \`scripts/src/relay.ts\`):
Pyth Hermes when \`PYTH_API_KEY\` is set, otherwise the ECB reference rates from Frankfurter
(daily) and a static, labelled reference for gold and silver. Production reads Pyth price accounts on-chain.

| What | Address |
|---|---|
| Program | ${ex(out.programId)} |
| Admin / upgrade authority | ${ex(out.admin)} |
| Config | ${ex(out.config)} |
| DemoState | ${ex(out.demoState)} |
| Test USDC (SPL Token, 6dp) | ${ex(out.mints.usdc)} |
| Test USDG (Token-2022, 6dp, metadata) | ${ex(out.mints.usdg)} |
| Faucet mint authority | ${ex(out.faucetMintAuthority)} |
| Vault USDC / USDG | ${ex(out.vaults.usdc)} / ${ex(out.vaults.usdg)} |
| Insurance USDC / USDG | ${ex(out.insurance.usdc)} / ${ex(out.insurance.usdg)} |
| Maker (seeded offers) | ${ex(out.maker)} |
| Keeper | ${ex(out.keeper)} |

## Markets

| id | Market | Market PDA |
|---|---|---|
${out.markets.map((m) => `| ${m.id} | ${m.symbol} | \`${m.address}\` |`).join("\n")}

## Offers

${offers.length} maker offers (USDC on all 15 markets, both sides; USDG on the 5 demo markets).
Capacity $250k each, spread 15 bps majors / 40 bps TRY, EM and metals. Tenors: the program allows
1–365 days; the seeded offers quote 7–180 days.

The faucet mint authority pays ATA rent on every app faucet request (10,000 test USDC + 10,000 test
USDG). It is seeded with 3 SOL (\`FAUCET_SOL\`); top it up when the faucet starts failing.
`;
  writeFileSync(join(ROOT, "docs/devnet.md"), md);
  console.log("wrote docs/devnet.md");
}

main().catch((e) => { console.error(e); process.exit(1); });
